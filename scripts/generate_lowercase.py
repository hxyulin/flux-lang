#!/usr/bin/env python3
"""Generate Flux's Unicode 17 lowercase data from pinned Rust source.

Run: python3 scripts/generate_lowercase.py [--check] [--source unicode_data.rs]
The selected stable rustc compiles its generated Unicode data as ordinary Rust;
no unstable compiler flags, bootstrap, network downloads, or dependencies.
Rust's unicode_data.rs is generated by src/tools/unicode-table-generator and is
licensed under Apache-2.0 OR MIT. Its Unicode data is version 17.0.0.
"""
import argparse
import bisect
import hashlib
from pathlib import Path
import subprocess
import tempfile

SOURCE_SHA256 = "d3d218b7574f08efe423e9d4b6b539e700046aca4f2a2793d38164ec5a1b00b2"
ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "library/alloc/src/str/lowercase_data.rs"


def properties(points):
    ranges = []
    for point in sorted(points):
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], point)
        else:
            ranges.append((point, point))
    return ranges


def simple_ranges(mapping):
    pairs = sorted((a, b[0]) for a, b in mapping.items() if len(b) == 1)
    result = []
    i = 0
    while i < len(pairs):
        start, output = pairs[i]
        end = start
        stride = 1
        j = i + 1
        if j < len(pairs):
            distance = pairs[j][0] - start
            if distance in (1, 2) and pairs[j][1] - pairs[j][0] == output - start:
                stride = distance
                while j < len(pairs) and pairs[j][0] == end + stride and pairs[j][1] - pairs[j][0] == output - start:
                    end = pairs[j][0]
                    j += 1
        result.append((start, end, stride, output))
        i = j
    return result


def find(ranges, starts, point):
    index = bisect.bisect_right(starts, point) - 1
    if index >= 0 and point <= ranges[index][1]:
        return ranges[index]
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source", type=Path)
    args = parser.parse_args()
    source = args.source
    if source is None:
        sysroot = subprocess.check_output(["rustc", "--print", "sysroot"], text=True).strip()
        source = Path(sysroot) / "lib/rustlib/src/rust/library/core/src/unicode/unicode_data.rs"
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"unexpected Unicode source hash {digest}; expected {SOURCE_SHA256}")
    with tempfile.TemporaryDirectory(prefix="flux-unicode-") as directory:
        driver = Path(directory) / "read.rs"
        executable = Path(directory) / "read"
        # The pinned file calls assume only after proving array bounds. This
        # checked replacement avoids access to Rust compiler-private intrinsics.
        driver.write_text('''pub use std::{ops, cmp};
mod intrinsics { pub const fn assume(value:bool) { assert!(value); } }
#[path=SOURCE] mod data;
fn main(){
 assert_eq!(data::UNICODE_VERSION,(17,0,0));
 for point in 0..=0x10ffffu32 { if let Some(c)=char::from_u32(point) {
  let lower=data::conversions::to_lower(c);
  if point>=128 && lower!=[c,'\\0','\\0'] { println!("L {} {} {} {}",point,lower[0] as u32,lower[1] as u32,lower[2] as u32); }
  let cased=c.is_ascii_alphabetic() || (point>=170 && (data::lowercase::lookup(c)||data::uppercase::lookup(c)||data::lt::lookup(c)));
  if cased { println!("C {}",point); }
  let ignorable=if c.is_ascii(){matches!(c,'\\''|'.'|':'|'^'|'`')}else{data::case_ignorable::lookup(c)};
  if ignorable { println!("I {}",point); }
 }}
}
'''.replace("SOURCE", '"' + str(source.resolve()) + '"'))
        subprocess.run(["rustc", "--edition=2024", "-Awarnings", "-O", str(driver), "-o", str(executable)], check=True)
        lines = subprocess.check_output([str(executable)], text=True).splitlines()
    mapping, cased, ignorable = {}, set(), set()
    for line in lines:
        kind, *values = line.split()
        values = list(map(int, values))
        if kind == "L":
            mapping[values[0]] = tuple(v for v in values[1:] if v)
        else:
            (cased if kind == "C" else ignorable).add(values[0])
    ranges = simple_ranges(mapping)
    multi = {c: v for c, v in mapping.items() if len(v) > 1}
    cased_ranges, ignorable_ranges = properties(cased), properties(ignorable)
    starts = [row[0] for row in ranges]
    cased_starts = [row[0] for row in cased_ranges]
    ignorable_starts = [row[0] for row in ignorable_ranges]
    # Exhaustively verify compression against every original scalar property
    # and mapping, including gaps and the parity holes in stride-two ranges.
    for point in range(0x110000):
        if 0xd800 <= point <= 0xdfff:
            continue
        actual = (point,)
        row = find(ranges, starts, point)
        if row and (point - row[0]) % row[2] == 0:
            actual = (row[3] + point - row[0],)
        actual = multi.get(point, actual)
        assert actual == mapping.get(point, (point,)), hex(point)
        assert bool(find(cased_ranges, cased_starts, point)) == (point in cased), hex(point)
        assert bool(find(ignorable_ranges, ignorable_starts, point)) == (point in ignorable), hex(point)
    output = [
        "//! Generated Unicode 17.0.0 data. Regenerate with scripts/generate_lowercase.py.",
        "//! Derived from Rust core/src/unicode/unicode_data.rs (Apache-2.0 OR MIT).",
        f"//! Source SHA-256: {SOURCE_SHA256}",
        f"//! {len(mapping)} non-ASCII mappings; {len(cased)} Cased and {len(ignorable)} Case_Ignorable scalars.",
        "", "// (first, last, stride, mapped first); unmatched parity remains unchanged.",
        f"pub(super) static SIMPLE: [(u32, u32, u32, u32); {len(ranges)}] = [",
    ]
    output += [f"    (0x{a:x}, 0x{b:x}, {stride}, 0x{mapped:x})," for a, b, stride, mapped in ranges]
    output += ["];", "", f"pub(super) static MULTI: [(char, &str); {len(multi)}] = ["]
    for point, mapped in sorted(multi.items()):
        text = "".join("\\u{" + f"{c:x}" + "}" for c in mapped)
        output.append(f"    ('\\u{{{point:x}}}', \"{text}\"),")
    output += ["];", ""]
    for name, rows in [("CASED", cased_ranges), ("CASE_IGNORABLE", ignorable_ranges)]:
        output += [f"pub(super) static {name}: [(u32, u32); {len(rows)}] = ["]
        output += [f"    (0x{a:x}, 0x{b:x})," for a, b in rows]
        output += ["];", ""]
    text = "\n".join(output)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit(f"generated Unicode data differs: {OUTPUT}")
    else:
        OUTPUT.write_text(text)
    print(f"verified 1,112,064 scalars; {len(mapping)} mappings in {len(ranges)} simple ranges and {len(multi)} expansions")


if __name__ == "__main__":
    main()
