fn classify(x: u8, pair: (u8, u8)) {
    match x {
        (..=5) => (),
        (..10) => (),
        ((..=20)) => (),
        (30..=40) => (),
        (50..) => (),
        _ => (),
    }
    match pair {
        (..=5, _) => (),
        (..10, _) => (),
        (.., 20) => (),
        (30, ..) => (),
        (..) => (),
    }
    let (..=5,) = (x,) else { return };
}
